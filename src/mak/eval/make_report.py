"""Build results/classifier/report.md from saved summaries (no hand-copied numbers). OWNER: Jabin.
python -m mak.eval.make_report
"""
import json

from mak import config

R = config.RESULTS_DIR
QS = ("gender_signal", "topic", "family", "stat", "format")


def summ(folder, arm, lang):
    p = R / "classifier" / folder / f"{arm}_{lang}_summary.json"
    if not p.exists():
        return None
    return {r["q"]: r for r in json.loads(p.read_text(encoding="utf-8"))["by_q_lang"]}


def cell(r):
    return f"{r['acc']:.3f} ({r['lo']:.2f}-{r['hi']:.2f})" if r else "-"


def block(title, folder, arms, note):
    L = [f"### {title}", "", note, "", "| arm | lang | n | " + " | ".join(QS) + " |", "|---|---|---|" + "---|" * len(QS)]
    for arm, label in arms:
        for lang in ("en", "hi", "ta"):
            s = summ(folder, arm, lang)
            if s:
                n = s["gender_signal"]["n"]
                L.append(f"| {label} | {lang} | {n} | " + " | ".join(cell(s.get(q)) for q in QS) + " |")
    return L + [""]


def e4():
    L = ["### E4 end-to-end decision accuracy (query -> understand -> catalogue -> decide())", "",
         "| system | en | hi | ta |", "|---|---|---|---|"]
    for name, label in (("rules_official", "rules only"), ("shipped_v3_posthoc", "shipped Laya v3 (post-hoc, pre-rubric rules)"),
                        ("shipped_v3r_posthoc", "shipped Laya v3 + rubric-aligned rules (post-hoc) [SHIPPED]"),
                        ("shipped_v4_posthoc", "shipped Laya v4 + rubric-aligned rules (post-hoc, not chosen)")):
        p = R / "e4" / f"{name}.json"
        if p.exists():
            o = json.loads(p.read_text(encoding="utf-8"))["overall"]
            L.append(f"| {label} | " + " | ".join(f"{o[l]['acc']:.3f} ({o[l]['ci'][0]:.2f}-{o[l]['ci'][1]:.2f})" for l in ("en", "hi", "ta")) + " |")
    return L + [""]


def e3():
    L = ["### E3 cross-sport transfer (testsets/xsport.csv; untouched test, run once with Laya v3)", "",
         "| arm | gender en | topic en | n en |", "|---|---|---|---|"]
    for arm in ("rules", "laya_ft", "shipped"):
        p = R / "e3" / f"xsport_{arm}_summary.json"
        if p.exists():
            s = {(r["q"], r["lang"]): r for r in json.loads(p.read_text(encoding="utf-8"))["by_q_lang"]}
            g, t = s.get(("gender_signal", "en")), s.get(("topic", "en"))
            L.append(f"| {arm} | {cell(g)} | {cell(t)} | {g['n'] if g else '-'} |")
    return L + ["", "Tamil xsport has n=1: not interpretable.", ""]


def main():
    arms_off = [("a_rules", "a rules"), ("b_laya_zeroshot", "b Laya zero-shot"), ("c_laya_ft", "c Laya fine-tuned v2"),
                ("d_shipped", "d shipped (Laya v2 + rules)"), ("e_qwen_lora", "e Qwen2.5-1.5B LoRA"), ("f_xlmr_ft", "f xlm-roberta-base")]
    md = ["# Classifier evaluation report (Make AI Know Her)", "",
          "Generated by `python -m mak.eval.make_report` from saved summaries. Cells: accuracy (Wilson 95% CI). "
          "Test sets: Joanna's frozen testsets/nlu_{en,hi,ta}.csv (testsets/FROZEN.md): real NQ-open queries (en), Aya native "
          "prompts (hi/ta, small), IndicTrans2 translations, held-out generated hard cases; one same-agent reviewer, no human "
          "or native-speaker validation (K-P2 handoff).", "",
          "## Read this first (honesty notes)",
          "1. The OFFICIAL single run (TEST_RUN.lock) used the v2 models. It is ALSO the model-selection run (disclosed per the "
          "K-P2 handoff and PREREGISTRATION).",
          "2. v3/v4 and the rubric-aligned rules were changed AFTER the official run using aggregate slice/confusion counts "
          "only (no test text read). Their numbers are POST-HOC and test-informed, never a held-out claim.",
          "3. Shipped = Laya v3 + rules, chosen by a rule written before v4 results (docs/05): v3 .726 vs v4 .701 mean "
          "(gender, family, stat). v4 had better E4 decisions; disclosed, not used to switch.",
          "4. Gate G4 (gender >= 98% per language) is NOT met on real queries. Label conventions: the test labels follow the "
          "product rubric; earlier training templates differed (weak cues, Hindi feminine forms, league names) and were "
          "aligned in data v3/v4 (G-022, G-027).",
          "5. Accuracy on synthetic, translated or generated rows is not native-user accuracy. No real voice transcripts exist; "
          "voice robustness is measured only on a synthetic dev slice.", ""]
    md += block("Official single test run (v2 models, all baselines a-e + xlm-r)", "test", arms_off,
                "MEASURED 3-4 Oct 2026 on RTX 5060; GENDER_THRESHOLD 0.98, merge v2 (pre-test rules, docs/05).")
    md += block("Post-hoc: Laya v3 (TEST-INFORMED)", "posthoc_v3", [("c_laya_ft", "Laya v3 alone"), ("d_shipped", "shipped v3 (pre-rubric rules)")],
                "Threshold 0.85.")
    md += block("Post-hoc: rubric-aligned rules (TEST-INFORMED)", "posthoc_v3r", [("a_rules", "rules (no league men-cues)"), ("d_shipped", "shipped v3 [SHIPPED]")], "")
    md += block("Post-hoc: Laya v4 (TEST-INFORMED, not chosen)", "posthoc_v4", [("c_laya_ft", "Laya v4 alone"), ("d_shipped", "shipped v4")], "")
    md += e4() + e3()
    md += ["## What these numbers do not prove",
           "- Real fan traffic, voice-assistant transcripts or native-speaker phrasing beyond the small Aya subset.",
           "- That the answers shown to users are correct: that is E1 (results/e1/) plus the verified facts layer.",
           "- Generalisation to stats outside the 25 golden intents (those get 'unsupported' / guidance)."]
    out = R / "classifier" / "report.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
